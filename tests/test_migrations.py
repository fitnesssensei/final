"""Тесты миграций: `alembic upgrade head` создаёт ровно схему моделей."""

from pathlib import Path

from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, inspect

from keitaro_wrapper.db import Base

PROJECT_ROOT = Path(__file__).resolve().parents[1]


def make_config(tmp_path: Path) -> tuple[Config, str, str]:
    """Готовит конфиг Alembic на файловой SQLite и возвращает sync/async URL."""
    async_url = f"sqlite+aiosqlite:///{tmp_path / 'migrations.db'}"
    config = Config(str(PROJECT_ROOT / "alembic.ini"))
    config.set_main_option("sqlalchemy.url", async_url)
    return config, async_url, async_url.replace("+aiosqlite", "")


def test_upgrade_creates_model_schema(tmp_path: Path) -> None:
    """Таблицы и колонки после `upgrade head` совпадают с моделями.

    Сравнение с `Base.metadata` ловит дрейф: миграцию забыли обновить после
    правки модели, и тесты репозиториев на `create_all` этого не заметят.
    """
    config, _, sync_url = make_config(tmp_path)

    command.upgrade(config, "head")

    engine = create_engine(sync_url)
    try:
        inspector = inspect(engine)
        assert set(Base.metadata.tables) | {"alembic_version"} == set(inspector.get_table_names())
        for table in Base.metadata.sorted_tables:
            actual_columns = {column["name"] for column in inspector.get_columns(table.name)}
            assert actual_columns == set(table.columns.keys())
        assert inspector.get_pk_constraint("operation_log")["constrained_columns"] == ["id"]
        assert inspector.get_pk_constraint("geo_map")["constrained_columns"] == ["code"]
    finally:
        engine.dispose()


def test_downgrade_removes_all_tables(tmp_path: Path) -> None:
    """`downgrade base` возвращает пустую БД — миграция обратима."""
    config, _, sync_url = make_config(tmp_path)
    command.upgrade(config, "head")

    command.downgrade(config, "base")

    engine = create_engine(sync_url)
    try:
        remaining = set(inspect(engine).get_table_names())
        assert not set(Base.metadata.tables) & remaining
    finally:
        engine.dispose()


def test_models_match_migration_without_new_diffs(tmp_path: Path) -> None:
    """Autogenerate после `upgrade head` не находит изменений схемы.

    `alembic check` молча выходит, если модели и миграции совпадают, и падает
    с `AutogenerateDiffsDetected`, если миграцию забыли обновить.
    """
    config, _, _ = make_config(tmp_path)
    command.upgrade(config, "head")

    command.check(config)
